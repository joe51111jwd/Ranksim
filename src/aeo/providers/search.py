"""Pluggable web search. Brave is live; the mock returns labeled synthetic pages."""

from __future__ import annotations

import httpx

from aeo.providers.types import SearchHit

BRAVE_ENDPOINT = "https://api.search.brave.com/res/v1/web/search"


class SearchProvider:
    name = "base"
    synthetic = False

    def search(self, query: str, count: int = 5) -> list[SearchHit]:
        raise NotImplementedError


class NullSearchProvider(SearchProvider):
    """Explicitly disabled competitor search. Returns nothing and invents nothing."""

    name = "none"
    synthetic = False

    def search(self, query: str, count: int = 5) -> list[SearchHit]:
        return []


class MockSearchProvider(SearchProvider):
    """Deterministic rival pages for tests and offline runs.

    Hits are tagged ``synthetic=True``. They are not live web results and must
    not be described as Google, Bing, or Brave rankings.
    """

    name = "mock"
    synthetic = True

    def search(self, query: str, count: int = 5) -> list[SearchHit]:
        question = " ".join(query.split())
        stubs = [
            (
                "https://rival-outdoor.example/roundup",
                "A roundup from Rival Outdoor",
                f"People sometimes ask '{question}'. This mock page lists generic outdoor snacks without a firm recommendation.",
            ),
            (
                "https://fieldnotes.example/snacks",
                "Field Notes snacks",
                f"Field notes mention '{question}' once. This synthetic page is a short competing stub, not a live web result.",
            ),
            (
                "https://packlist.example/guides",
                "Packlist guide",
                f"Packlist stub for '{question}'. Synthetic competitor used when a live search provider is not configured.",
            ),
        ]
        hits: list[SearchHit] = []
        for url, title, body in stubs[: max(0, count)]:
            html = (
                "<!doctype html><html><head>"
                f"<title>{title}</title>"
                '<meta name="description" content="Synthetic mock search result. Not a live web page.">'
                f'<link rel="canonical" href="{url}"></head><body>'
                f"<h1>{title}</h1><p>{body}</p>"
                "<p>Provider: mock. This HTML was generated by the simulator, not fetched from the web.</p>"
                "</body></html>"
            )
            hits.append(
                SearchHit(
                    url=url,
                    title=title,
                    snippet=body,
                    provider=self.name,
                    synthetic=True,
                    inline_html=html,
                )
            )
        return hits


class BraveSearchProvider(SearchProvider):
    """Brave Search API adapter. Results are live URLs with no inline HTML."""

    name = "brave"
    synthetic = False

    def __init__(self, api_key: str, client: httpx.Client | None = None, timeout: float = 20.0) -> None:
        self.api_key = api_key
        self._owns_client = client is None
        self.client = client or httpx.Client(timeout=httpx.Timeout(timeout))

    def close(self) -> None:
        if self._owns_client:
            self.client.close()

    def search(self, query: str, count: int = 5) -> list[SearchHit]:
        response = self.client.get(
            BRAVE_ENDPOINT,
            params={"q": query, "count": max(1, min(count, 20))},
            headers={
                "X-Subscription-Token": self.api_key,
                "Accept": "application/json",
            },
        )
        response.raise_for_status()
        payload = response.json()
        results = ((payload.get("web") or {}).get("results")) or []
        hits: list[SearchHit] = []
        for item in results:
            url = item.get("url")
            if not isinstance(url, str) or not url:
                continue
            hits.append(
                SearchHit(
                    url=url,
                    title=str(item.get("title") or ""),
                    snippet=str(item.get("description") or ""),
                    provider=self.name,
                    synthetic=False,
                    inline_html=None,
                )
            )
            if len(hits) >= count:
                break
        return hits
