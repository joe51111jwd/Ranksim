"""Power and pass-probability estimates for T1 candidate specs (design days only). PREDICTED.

Two readings, both assuming the held-out effect equals the design effect:

1. Analytic rows needed for 80% power that the query-bootstrap 95% lower bound of
   (model - best baseline) is above 0: n = (1.96 + 0.84)^2 * var(d) * deff / diff^2,
   where d is the per-row paired hit difference against the baseline that is best on
   the pooled design rows, and deff is the cluster design effect (bootstrap variance by
   (day, query) cluster over the iid variance).
2. Simulated held-out days: draw (day, query) clusters with replacement from the design
   rows until the target row count, score with metrics.bootstrap_difference against the
   best baseline of the simulated day, and count passes.

  python scripts/claude/t1_power.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.claude import metrics as m  # noqa: E402
from scripts.claude import t1_common as c  # noqa: E402
from scripts.claude import t1_design_eval as ev  # noqa: E402
from scripts.claude import t1_placement as t1  # noqa: E402

OUT = ev.OUT_DIR / "power.json"
CANDIDATES = {
    "new": ["frozen:params.json", "clip47:dp|deep_last", "top4:dp<=3|deep_last"],
    "reentrant": ["frozen:params.json", "reclip38:deep_last", "reclip29:deep_last"],
}
SIM_N = (30, 60, 120)
SIM_REPS = 300
SIM_DRAWS = 500


def hit_frame(frame: pd.DataFrame, params: dict) -> pd.DataFrame:
    frame = frame.copy()
    frame["pred"] = ev.predict_table(frame, params)
    out = frame[["day", "query"]].copy()
    out["cluster"] = frame["day"].astype(str) + "|" + frame["query"]
    for name, fn in ev.METRICS.items():
        out[f"{name}_model"] = [int(fn(p, t)) for p, t in zip(frame["pred"], frame["truth"], strict=True)]
        for base in ev.BASELINES:
            out[f"{name}_{base}"] = [int(fn(p, t)) for p, t in zip(frame[base], frame["truth"], strict=True)]
    return out


def analytic(h: pd.DataFrame, metric: str, rng: np.random.Generator) -> dict:
    best = max(ev.BASELINES, key=lambda b: h[f"{metric}_{b}"].sum())
    d = (h[f"{metric}_model"] - h[f"{metric}_{best}"]).to_numpy(dtype=float)
    diff, var = float(d.mean()), float(d.var(ddof=1))
    sums = pd.Series(d).groupby(h["cluster"].to_numpy()).agg(["sum", "size"])
    idx = rng.integers(0, len(sums), size=(2000, len(sums)))
    boot = sums["sum"].to_numpy()[idx].sum(axis=1) / sums["size"].to_numpy()[idx].sum(axis=1)
    deff = float(boot.var() / (var / len(d))) if var > 0 else float("nan")
    need = (1.96 + 0.84) ** 2 * var * max(deff, 1.0) / diff**2 if diff > 0 else float("inf")
    return {"best_baseline": best, "diff": diff, "var_d": var, "deff": deff, "n_for_80pct_power": need, "n": int(len(d))}


def simulate(h: pd.DataFrame, n_rows: int, rng: np.random.Generator) -> dict:
    clusters = {key: g for key, g in h.groupby("cluster")}
    keys = list(clusters)
    passes = {"band3": 0, "err3": 0, "both": 0}
    for rep in range(SIM_REPS):
        parts, total, j = [], 0, 0
        while total < n_rows:
            key = keys[rng.integers(0, len(keys))]
            part = clusters[key].copy()
            part["query"] = f"s{j}"  # each draw is its own query cluster
            parts.append(part)
            total += len(part)
            j += 1
        day = pd.concat(parts, ignore_index=True)
        ok = {}
        for metric in ("band3", "err3"):
            best = max(ev.BASELINES, key=lambda b: day[f"{metric}_{b}"].sum())
            res = m.bootstrap_difference(day, f"{metric}_model", f"{metric}_{best}", draws=SIM_DRAWS, seed=1000 + rep)
            ok[metric] = res["lo"] > 0
            passes[metric] += int(ok[metric])
        passes["both"] += int(ok["band3"] and ok["err3"])
    return {k: v / SIM_REPS for k, v in passes.items()}


def main() -> None:
    design = ev.add_baselines(c.design_table())
    emu = ev.add_baselines(c.emulation_table())
    pools = {
        "all-design": design,
        # Nov 17 o30 enters once, through the a70 emulation (same outcome rows, a70-style history)
        "consensus-like (o30 Nov 16 + a70 emulation of Nov 17)": pd.concat(
            [design[(design["grp"] == "o30") & (design["day"] == "2026-11-16")], emu.assign(day="emu")], ignore_index=True
        ),
    }
    variants = ev.fixed_variants()
    variants["frozen:params.json"] = t1.load_params()
    rng = np.random.default_rng(20261119)
    report = {}
    lines = ["# T1 power and pass probability (PREDICTED, design days only)", "", "Generated by scripts/claude/t1_power.py.", ""]
    lines += ["| class | spec | pool | metric | best baseline | design diff | var(d) | deff | rows for 80% power | P(pass) n=30 | n=60 | n=120 |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for klass, names in CANDIDATES.items():
        for name in names:
            for pool_name, pool in pools.items():
                sub = pool[pool["klass"] == klass]
                h = hit_frame(sub, variants[name])
                sims = {n: simulate(h, n, rng) for n in SIM_N}
                entry = {"sim": sims}
                for metric in ("band3", "err3"):
                    a = analytic(h, metric, rng)
                    entry[metric] = a
                    need = "inf" if not np.isfinite(a["n_for_80pct_power"]) else f"{a['n_for_80pct_power']:.0f}"
                    lines.append(
                        f"| {klass} | {name} | {pool_name} | {metric} | {a['best_baseline'][2:]} | {a['diff']:+.3f} (n={a['n']}) | {a['var_d']:.3f} | "
                        f"{a['deff']:.2f} | {need} | {sims[30][metric]:.2f} | {sims[60][metric]:.2f} | {sims[120][metric]:.2f} |"
                    )
                lines.append(
                    f"| {klass} | {name} | {pool_name} | BOTH | | | | | | {sims[30]['both']:.2f} | {sims[60]['both']:.2f} | {sims[120]['both']:.2f} |"
                )
                report.setdefault(klass, {}).setdefault(name, {})[pool_name] = entry
    OUT.write_text(json.dumps(report, indent=1, sort_keys=True, default=float))
    (ev.OUT_DIR / "power.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
